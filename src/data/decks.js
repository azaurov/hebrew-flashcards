/* ---------------- build decks ---------------- */
function sizeFor(s){
  const n = s.replace(/[֑-ׇ]/g,'').length;
  if(n <= 4)  return 'xl';
  if(n <= 9)  return 'lg';
  if(n <= 20) return 'md';
  return 'sm';
}

